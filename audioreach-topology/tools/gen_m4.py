"""Generate the HP-tuned module m4 files for the OmniBook Ultra 14 (8F03)
speaker topology from HP's ACDB.

  gen_m4.py ACDB OUTDIR

Writes OUTDIR/audioreach/:
  module_speaker_protection_hp8f03.m4     SP v5 RX, HP's records
  module_speaker_protection_vi_hp8f03.m4  SP v5 VI, HP's records
  module_hp_pp_hp8f03.m4                  HP's speaker post-processing chain
  module_msiir_hpf_hp8f03.m4              tweeter high-pass (computed, no HP data)

The output carries HP's tuning data: keep it local.
"""
import argparse
import math
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from acdb import Acdb  # noqa: E402

# Speaker device subgraph and HP's device post-processing subgraph
SG_DEVICE, SG_PP = 0xB0000001, 0xB0000075
MID_SP, MID_VI = 0x070010E2, 0x070010E3
MID_MSPP, MID_SAL, MID_CHMIXER = 0x0701000D, 0x07001010, 0x07001013
IID_MSPP, IID_SAL, IID_CHMIX_SPLIT = 0x4AB0, 0x47F5, 0x4AAF

SPEAKERS = ("WooferLeft", "TweeterLeft", "WooferRight", "TweeterRight")

# Thermal targets, degC, lane order. HP ships 100/90; 10 K lower keeps margin
# against the voice-coil temperatures measured at the kernel's gain limit.
TEMP_TARGET_C = (90, 80, 90, 80)

# Delivered full scale (V peak at 0 dBFS), lane order. Must equal the device
# tree's qcom,speaker-full-scale-microvolt: the kernel refuses the graph if a
# speaker differs by more than 1 %. HP's ACDB has 13-15 V, the Windows gain.
FULL_SCALE_V = (3.246, 3.387, 3.283, 3.234)

PID_SP_STATIC = 0x080011E8
PID_SP_DYNAMIC = 0x08001532  # param_id_sp_dynamic_cfg_t, spf/api/modules/sp_rx.h
PID_VI_STATIC = 0x080011F6
PID_VI_THERMAL = 0x08001535

# param_id_sp_dynamic_cfg_t: 284 B common part, then 4 x sp_th_ctrl_param_t (40 B)
TH_BASE, TH_SIZE, TH_TEMP_TGT = 284, 40, 7
HP_TEMP_TARGET_Q6 = (6400, 5760, 6400, 5760)

# (module, param id, word, HP value, new value, reason)
SP_OVERRIDES = [
    ("sp", PID_SP_STATIC, 5, 1, 0, "tuning_mode_en_flag: RTM tuning/logging mode"),
    ("vi", PID_VI_STATIC, 8, 1, 0, "ex_tuning_mode_enable_flag: excursion dump for tuning tools"),
]
for _k, _t in enumerate(TEMP_TARGET_C):
    SP_OVERRIDES.append(("sp", PID_SP_DYNAMIC, (TH_BASE + TH_SIZE * _k + 4 * TH_TEMP_TGT) // 4,
                         HP_TEMP_TARGET_Q6[_k], int(round(_t * 64)),
                         "%s temp_tgt_q6 -> %d C" % (SPEAKERS[_k], _t)))

# Left out of the tested graph: both configure the same HP-only feature.
SP_DROPPED = [("sp", 0x08001AEC), ("sp", 0x08001AEB)]

MSPP_RECORDS = [0x08001026, 0x080010A6, 0x0800137B, 0x0800137C, 0x08001394, 0x08001505, 0x08001ABC]
SAL_RECORDS = [0x08001047, 0x08001050]
PID_CHMIXER_COEFF = 0x0800101F
PID_CHMIXER_OUT_CH_CFG = 0x0800103B

PID_MODULE_ENABLE = 0x08001026
PID_MSIIR_ENABLE = 0x08001020
PID_MSIIR_CONFIG = 0x08001022
MSIIR_FC, MSIIR_STAGES, MSIIR_SHIFT, FS = 1500.0, 2, 2, 48000.0

FL, FR, LS, RS, LFE, LB, RB, LFE2 = 1, 2, 4, 5, 6, 8, 9, 17
ONE_Q14 = 0x4000

HEADER = """# Generated by gen_m4.py from HP's ACDB. Contains HP tuning data; not for redistribution.
include(`util/util.m4') dnl
"""


def u32(b, w):
    return struct.unpack_from("<I", b, 4 * w)[0]


def vfs_overrides(vi):
    """VI v_full_sc_q10: low half of word 1 + 8k + 4 of the thermal record."""
    rec = vi[PID_VI_THERMAL]
    out = []
    for k, v in enumerate(FULL_SCALE_V):
        w = 1 + 8 * k + 4
        old = u32(rec, w)
        out.append(("vi", PID_VI_THERMAL, w, old, (old & 0xFFFF0000) | int(round(v * 1024)),
                    "%s v_full_sc -> %.3f V" % (SPEAKERS[k], v)))
    return out


def apply(key, recs, overrides):
    recs = {p: bytearray(d) for p, d in recs.items()}
    for mod, pid, w, old, new, _ in overrides:
        if mod != key:
            continue
        cur = u32(recs[pid], w)
        if cur != old:
            raise SystemExit("ACDB %s 0x%08x word %d: expected %#x, found %#x (not the 8F03 tuning?)"
                             % (mod, pid, w, old, cur))
        struct.pack_into("<I", recs[pid], 4 * w, new)
    for mod, pid in SP_DROPPED:
        if mod == key:
            del recs[pid]
    return sorted(recs.items())


def cfg_words(recs, iid_tok):
    """Module cfg blob: struct audioreach_module_priv_data header, then
    {iid, param id, size, 0, payload padded to 4 B} per record."""
    body, nbytes = [], 0
    for pid, data in recs:
        padded = bytes(data) + b"\0" * (-len(data) % 4)
        body += [iid_tok, "0x%08x" % pid, "0x%08x" % len(data), "0x00000000"]
        body += ["0x%08x" % w for w in struct.unpack("<%dI" % (len(padded) // 4), padded)]
        nbytes += 16 + len(padded)
    return ["0x%08x" % nbytes, "0x01001006", "0x00000000", "0x00000000"] + body


# alsatplg takes at most 16384 words per SectionData; the widget's data
# sections are concatenated, so a long blob is split across several
SECTION_WORDS = 16000


def cfg_sections(words, name):
    text, names = "", []
    for k in range(0, len(words), SECTION_WORDS):
        chunk = words[k:k + SECTION_WORDS]
        lines = [",".join(chunk[i:i + 4]) for i in range(0, len(chunk), 4)]
        sec = "%s%s" % (name, "" if not k else k // SECTION_WORDS)
        names.append(sec)
        text += ("`SectionData.\"NAME_PREFIX.%s\" {'\n`        words \"%s\"'\n`}'\n`'\n"
                 % (sec, ",'\n`               ".join(lines)))
    return text, names


