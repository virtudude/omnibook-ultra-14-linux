def chmix_table(out_map, in_map, rows):
    """One channel mixer coefficient table: rows[out] = {in_type: Q14 gain}."""
    b = struct.pack("<HH", len(out_map), len(in_map))
    b += struct.pack("<%dH" % len(out_map), *out_map) + struct.pack("<%dH" % len(in_map), *in_map)
    for o in out_map:
        b += struct.pack("<%dH" % len(in_map), *(rows.get(o, {}).get(i, 0) for i in in_map))
    return b


def chmix_coeff(*tables):
    return struct.pack("<I", len(tables)) + b"".join(tables)


def chmix_out(chmap):
    return struct.pack("<%dH" % (len(chmap) + 1), len(chmap), *chmap)


def gen_pp(acdb):
    """HP's Windows device post-processing (subgraph 0xb0000075):
    2->4 split -> SAL -> VOL_CTRL -> MSPP v5 -> SAL -> lane mixer."""
    mspp = [(p, acdb.record(SG_PP, IID_MSPP, MID_MSPP, p)) for p in MSPP_RECORDS]
    sal = [(p, acdb.record(SG_PP, IID_SAL, MID_SAL, p)) for p in SAL_RECORDS]
    # [L,R] (or a 4-channel PCM's [L,R,LS,RS]) -> MSPP's [L,R,LFE,LFE2], LFE pair silent
    split = [(PID_CHMIXER_COEFF, chmix_coeff(
                chmix_table([FL, FR, LFE, LFE2], [FL, FR], {FL: {FL: ONE_Q14}, FR: {FR: ONE_Q14}}),
                chmix_table([FL, FR, LFE, LFE2], [FL, FR, LS, RS], {FL: {FL: ONE_Q14}, FR: {FR: ONE_Q14}}))),
             (PID_CHMIXER_OUT_CH_CFG, chmix_out([FL, FR, LFE, LFE2]))]
    hp_split = acdb.record(SG_PP, IID_CHMIX_SPLIT, MID_CHMIXER, PID_CHMIXER_COEFF)
    if split[0][1][4:36] != hp_split[4:]:
        raise SystemExit("ACDB: HP's 2->4 channel mixer differs from the expected split")
    # MSPP's L/R are the tweeters and LFE/LFE2 the woofers; the SP chain
    # expects lane order [FL,LB,FR,RB] = WL, TL, WR, TR
    lanes = [(PID_CHMIXER_COEFF, chmix_coeff(
                chmix_table([FL, LB, FR, RB], [FL, FR, LFE, LFE2],
                            {FL: {LFE: ONE_Q14}, LB: {FL: ONE_Q14}, FR: {LFE2: ONE_Q14}, RB: {FR: ONE_Q14}}))),
             (PID_CHMIXER_OUT_CH_CFG, chmix_out([FL, LB, FR, RB]))]
    return "\n".join([
        HEADER + "define(`MODULE_ID_MSPP_V5', `0x0701000D') dnl\n"
        "define(`MODULE_ID_CHMIXER', `0x07001013') dnl\n"
        "define(`MODULE_ID_SAL', `0x07001010') dnl\n",
        pp_module("chsplit", "AR_MODULE_CHMIX_SPLIT_HP8F03", "MODULE_ID_CHMIXER", split),
        pp_module("salin", "AR_MODULE_SAL_IN_HP8F03", "MODULE_ID_SAL", sal),
        pp_module("salout", "AR_MODULE_SAL_OUT_HP8F03", "MODULE_ID_SAL", sal),
        SPK_VOL,
        pp_module("mspp", "AR_MODULE_MSPP_HP8F03", "MODULE_ID_MSPP_V5", mspp),
        pp_module("chlanes", "AR_MODULE_CHMIX_LANES_HP8F03", "MODULE_ID_CHMIXER", lanes)])


def q30(x):
    v = int(round(x * (1 << 30)))
    if not -(1 << 31) <= v < (1 << 31):
        raise SystemExit("coefficient %r does not fit Q30" % x)
    return v


def gen_msiir():
    """Tweeter high-pass: MSIIR (static module of the ADSP image) with
    MSIIR_STAGES identical Butterworth biquads (2 = LR4) at MSIIR_FC.
    Coefficients as iirTDF2_32() in audioreach-engine: b in Q(32 - shift),
    a in Q30; shift 2 makes all five Q30. The filter applies to every channel
    type except FL/FR, the woofer lanes, so no tweeter can bypass it."""
    w0 = 2 * math.pi * MSIIR_FC / FS
    c, s = math.cos(w0), math.sin(w0)
    alpha = s / (2 * (1 / math.sqrt(2)))
    a0 = 1 + alpha
    b0 = q30((1 + c) / 2 / a0)
    stage = [b0, -2 * b0, b0, q30(-2 * c / a0), q30((1 - alpha) / a0)]
    mask = 0xFFFFFFFF_FFFFFFFE & ~(1 << FL) & ~(1 << FR)
    lsb, msb = mask & 0xFFFFFFFF, mask >> 32
    cfg = struct.pack("<IIIHH", 1, lsb, msb, 0, MSIIR_STAGES)
    cfg += b"".join(struct.pack("<5i", *stage) for _ in range(MSIIR_STAGES))
    cfg += struct.pack("<%dh" % MSIIR_STAGES, *([MSIIR_SHIFT] * MSIIR_STAGES))
    cfg += b"\0" * (-len(cfg) % 4)
    recs = [(PID_MODULE_ENABLE, struct.pack("<I", 1)),
            (PID_MSIIR_ENABLE, struct.pack("<IIII", 1, lsb, msb, 1)),
            (PID_MSIIR_CONFIG, cfg)]
    return ("# SPDX-License-Identifier: BSD-3-Clause\n# Generated by gen_m4.py.\n"
            "include(`util/util.m4') dnl\n"
            + sp_module("AR_MODULE_MSIIR_HPF_HP8F03", "msiir", "0x07001014", "MSIIR_IID_HEX", recs))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("acdb")
    ap.add_argument("outdir")
    a = ap.parse_args()
    acdb = Acdb(a.acdb)
    sp_recs = acdb.module_records(SG_DEVICE, MID_SP)
    vi_recs = acdb.module_records(SG_DEVICE, MID_VI)
    ovr = SP_OVERRIDES + vfs_overrides(vi_recs)
    out = os.path.join(a.outdir, "audioreach")
    os.makedirs(out, exist_ok=True)
    files = {
        "module_speaker_protection_hp8f03.m4": HEADER + sp_module(
            "AR_MODULE_SP_HP8F03", "sp", "MODULE_ID_SPEAKER_PROTECTION", "SP_IID_HEX",
            apply("sp", sp_recs, ovr)),
        "module_speaker_protection_vi_hp8f03.m4": HEADER + sp_module(
            "AR_MODULE_SP_VI_HP8F03", "sp_vi", "MODULE_ID_SPEAKER_PROTECTION_VI", "SP_VI_IID_HEX",
            apply("vi", vi_recs, ovr)),
        "module_hp_pp_hp8f03.m4": gen_pp(acdb),
        "module_msiir_hpf_hp8f03.m4": gen_msiir(),
    }
    for name, text in files.items():
        with open(os.path.join(out, name), "w") as f:
            f.write(text)
    for mod, pid, w, old, new, why in ovr:
        print("  %s 0x%08x word %d: %d -> %d (%s)" % (mod, pid, w, old, new, why))


if __name__ == "__main__":
    main()
